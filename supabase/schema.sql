create table if not exists public.orders (
  id bigint generated by default as identity primary key,
  customer_id uuid references auth.users(id) on delete set null,
  customer_name text not null,
  customer_email text not null,
  customer_phone text,
  total numeric(10, 2) not null check (total >= 0),
  restaurant_slug text not null default 'samundri-food-house',
  order_type text not null default 'preorder' check (order_type in ('preorder', 'delivery')),
  scheduled_at timestamptz,
  delivery_address text,
  payment_method text not null default 'cash' check (payment_method in ('cash', 'bank', 'online')),
  payment_reference text,
  payment_status text not null default 'pending' check (payment_status in ('pending', 'verification_pending', 'paid', 'unavailable')),
  status text not null default 'pending' check (status in ('pending', 'accepted', 'preparing', 'ready', 'completed', 'cancelled')),
  created_at timestamptz not null default now()
);

