  customer_email text not null,
  event_type text not null,
  event_date date not null,
  guest_count integer not null check (guest_count between 8 and 28),
  requirements text not null,
  quote_amount numeric(10, 2),
  quote_note text,
  status text not null default 'enquiry_sent' check (status in ('enquiry_sent', 'quoted', 'accepted', 'declined_by_customer', 'rejected_by_restaurant', 'expired')),
  reject_reason text,
  created_at timestamptz not null default now()
);

